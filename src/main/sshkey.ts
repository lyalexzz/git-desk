import { createHash, generateKeyPairSync, randomBytes } from 'node:crypto'
import type { SshTarget } from '../shared/git'

function sshString(data: Buffer | string): Buffer {
  const buf = typeof data === 'string' ? Buffer.from(data, 'utf8') : data
  const len = Buffer.alloc(4)
  len.writeUInt32BE(buf.length)
  return Buffer.concat([len, buf])
}

function uint32(n: number): Buffer {
  const b = Buffer.alloc(4)
  b.writeUInt32BE(n >>> 0)
  return b
}

/** 不依赖 ssh-keygen 生成 ed25519 密钥，私钥为未加密的 openssh-key-v1 格式 */
export function generateEd25519(comment: string): { privateKey: string; publicKey: string } {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519')
  const pub = Buffer.from(publicKey.export({ format: 'jwk' }).x!, 'base64url')
  const seed = Buffer.from(privateKey.export({ format: 'jwk' }).d!, 'base64url')
  const pubBlob = Buffer.concat([sshString('ssh-ed25519'), sshString(pub)])

  const check = randomBytes(4).readUInt32BE()
  let priv = Buffer.concat([
    uint32(check),
    uint32(check),
    sshString('ssh-ed25519'),
    sshString(pub),
    sshString(Buffer.concat([seed, pub])),
    sshString(comment)
  ])
  const pad = (8 - (priv.length % 8)) % 8
  priv = Buffer.concat([priv, Buffer.from(Array.from({ length: pad }, (_, i) => i + 1))])

  const body = Buffer.concat([
    Buffer.from('openssh-key-v1\0', 'binary'),
    sshString('none'),
    sshString('none'),
    sshString(''),
    uint32(1),
    sshString(pubBlob),
    sshString(priv)
  ])
  const b64 = body.toString('base64').replace(/(.{70})/g, '$1\n').replace(/\n$/, '')
  return {
    privateKey: `-----BEGIN OPENSSH PRIVATE KEY-----\n${b64}\n-----END OPENSSH PRIVATE KEY-----\n`,
    publicKey: `ssh-ed25519 ${pubBlob.toString('base64')} ${comment}\n`
  }
}

export interface ParsedKey {
  type: string
  blob: string
  comment: string
}

export function parsePublicKey(text: string): ParsedKey | null {
  const m = /^\s*((?:ssh|ecdsa|sk)-[\w@.-]+)\s+([A-Za-z0-9+/]+={0,2})(?:\s+(.*))?$/.exec(text.trim().split(/\r?\n/)[0] ?? '')
  return m ? { type: m[1], blob: m[2], comment: (m[3] ?? '').trim() } : null
}

export function fingerprint(blob: string): string {
  return 'SHA256:' + createHash('sha256').update(Buffer.from(blob, 'base64')).digest('base64').replace(/=+$/, '')
}

export function sameKey(a: string, b: string): boolean {
  const x = parsePublicKey(a)
  const y = parsePublicKey(b)
  return Boolean(x && y && x.type === y.type && x.blob === y.blob)
}

/** 解析 git@host:group/x.git 或 ssh://git@host:2222/group/x.git */
export function parseSshUrl(url: string): SshTarget | null {
  const full = /^ssh:\/\/(?:([^@/]+)@)?(\[[^\]]+\]|[^:/]+)(?::(\d+))?\//i.exec(url)
  if (full) return { user: full[1] ?? 'git', host: full[2].replace(/^\[|\]$/g, ''), port: full[3] ? Number(full[3]) : 22 }
  const scp = /^(?:([^@/]+)@)?([^:/]+):(?!\/\/)/.exec(url)
  if (scp) return { user: scp[1] ?? 'git', host: scp[2], port: 22 }
  return null
}

export function validTarget(t: SshTarget): boolean {
  return /^[A-Za-z0-9.-]+$/.test(t.host) && /^[A-Za-z0-9._-]+$/.test(t.user) && Number.isInteger(t.port) && t.port > 0 && t.port < 65536
}

export function safeHostName(host: string): string {
  return host.toLowerCase().replace(/[^a-z0-9.-]/g, '_')
}

const beginMarker = (host: string) => `# >>> gitlab-desk ${host.toLowerCase()}`
const endMarker = (host: string) => `# <<< gitlab-desk ${host.toLowerCase()}`

export function sshConfigBlock(t: SshTarget, identityFile: string): string[] {
  return [
    beginMarker(t.host),
    '# Generated by GitLab Desk. This block is replaced when reconfigured.',
    `Host ${t.host}`,
    `  HostName ${t.host}`,
    `  Port ${t.port}`,
    `  User ${t.user}`,
    `  IdentityFile "${identityFile}"`,
    '  IdentitiesOnly yes',
    '  StrictHostKeyChecking accept-new',
    endMarker(t.host)
  ]
}

function splitLines(content: string): string[] {
  return content.replace(/^\uFEFF/, '').split(/\r?\n/)
}

/** 去掉本软件写入的配置块，返回剩余行以及配置块原来的位置 */
function withoutBlock(lines: string[], host: string): { rest: string[]; at: number } {
  const begin = beginMarker(host)
  const end = endMarker(host)
  const rest: string[] = []
  let at = -1
  let inside = false
  for (const line of lines) {
    if (line.trim() === begin) {
      inside = true
      if (at < 0) at = rest.length
      continue
    }
    if (inside) {
      if (line.trim() === end) inside = false
      continue
    }
    rest.push(line)
  }
  return { rest, at }
}

export function hasOwnBlock(content: string, host: string): boolean {
  return splitLines(content).some((l) => l.trim() === beginMarker(host))
}

/** 是否存在其他 Host 配置精确匹配该主机（OpenSSH 对每个参数取第一个匹配到的值） */
export function hasForeignHost(content: string, host: string): boolean {
  const { rest } = withoutBlock(splitLines(content), host)
  const h = host.toLowerCase()
  return rest.some((line) => {
    const m = /^\s*Host\s+(.+)$/i.exec(line)
    return Boolean(m && m[1].split(/\s+/).some((p) => p.replace(/^"|"$/g, '').toLowerCase() === h))
  })
}

/** 写入或替换本软件的配置块，保留文件中的其他内容、换行风格和 BOM */
export function mergeSshConfig(content: string, block: string[], host: string): string {
  const bom = content.startsWith('\uFEFF') ? '\uFEFF' : ''
  const eol = content.includes('\r\n') ? '\r\n' : content ? '\n' : '\r\n'
  const { rest, at } = withoutBlock(splitLines(content), host)
  while (rest.length && rest[rest.length - 1].trim() === '') rest.pop()
  let lines: string[]
  if (at >= 0 && at < rest.length) {
    lines = [...rest.slice(0, at), ...block, ...rest.slice(at)]
  } else {
    lines = rest.length ? [...rest, '', ...block] : [...block]
  }
  return bom + lines.join(eol) + eol
}

const STAGES: Record<string, { label: string; from: number; to: number }> = {
  'Counting objects': { label: '服务器统计对象', from: 0, to: 2 },
  'Compressing objects': { label: '服务器压缩对象', from: 2, to: 5 },
  'Receiving objects': { label: '下载对象', from: 5, to: 85 },
  'Resolving deltas': { label: '解析差异', from: 85, to: 95 },
  'Updating files': { label: '检出文件', from: 95, to: 100 },
  'Filtering content': { label: '下载 LFS 文件', from: 95, to: 100 }
}

/** 解析 git --progress 输出，例如 "Receiving objects:  45% (450/1000), 1.20 MiB | 500.00 KiB/s" */
export function parseProgress(line: string): { stage: string; percent: number; overall: number; detail: string } | null {
  const m = /^(?:remote:\s*)?([A-Za-z ]+?):\s+(\d{1,3})%(.*)$/.exec(line.trim())
  if (!m) return null
  const s = STAGES[m[1]]
  if (!s) return null
  const percent = Math.min(100, Number(m[2]))
  const speed = /\|\s*([\d.]+\s*[KMG]?i?B\/s)/.exec(m[3])?.[1]
  const size = /,\s*([\d.]+\s*[KMG]?i?B)\b/.exec(m[3])?.[1]
  return {
    stage: s.label,
    percent,
    overall: Math.round(s.from + ((s.to - s.from) * percent) / 100),
    detail: [size, speed].filter(Boolean).join(' · ')
  }
}
